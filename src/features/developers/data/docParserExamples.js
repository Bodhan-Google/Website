// Each example is a single composite image served from /public:
//   left portion  = the page scan with layout boxes + reading order
//   right portion = the model's OCR output
// `split` is the fraction of the image width where the divider sits, so the page
// can show the left portion and reveal the matching right portion inside the lens.
// Drop the files into: public/examples/docparser/
//
// `layout` re-attaches the model's own layout prediction — the numbered block
// labels burned into the left portion of each composite — to the `ocr` entries
// beneath it, so the text side can show the same blocks in the same order.
// `n` is the block's reading-order index on the scan; `span` is how many `ocr`
// entries that block covers (a List block holds several). Blocks the model
// found but transcribed as empty (the running headers) are not repeated here.
// Every composite is generated by the same script, which frames the page in a
// card and prints a caption above it. Each example's `crop` is that card's
// measured bounds inside the left portion — x/w as fractions of that portion's
// width, y/h as fractions of the image height — so the demo shows the page
// alone, without the caption or the surrounding margin.
